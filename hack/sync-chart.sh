#!/usr/bin/env bash
# Copies the parts of the Helm chart that must match config/ exactly: the
# CRDs, and the rules of every role. Run it after controller-gen; `make
# manifests` does both, and `make chart-check` fails if the chart is out of
# date.
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."
CHART=dist/chart/templates
HEADER="# Generated by hack/sync-chart.sh"

die() {
  echo "sync-chart: $*" >&2
  exit 1
}

# crd SRC DEST: wrap a CRD in the crds.install and crds.keep switches. keep
# protects it from helm uninstall; Argo CD renders the chart with helm
# template and ignores that, so the same switch also stops Argo CD pruning
# or deleting it.
crd() {
  local src=$1 dest=$2
  grep -q '{{' "$src" && die "$src contains {{, which Helm would read as a template"
  grep -q '^  annotations:$' "$src" || die "$src has no metadata.annotations to add keep to"
  {
    echo "$HEADER from $src. Don't edit."
    echo "{{- if .Values.crds.install }}"
    awk '
      NR == 1 && $0 == "---" { next }
      { print }
      /^  annotations:$/ && !done {
        print "    {{- if .Values.crds.keep }}"
        print "    helm.sh/resource-policy: keep"
        print "    argocd.argoproj.io/sync-options: Prune=false,Delete=false"
        print "    {{- end }}"
        done = 1
      }
    ' "$src"
    echo "{{- end }}"
  } >"$dest"
}

# role KIND SRC SUFFIX DEST [CONDITION]: a Role or ClusterRole named
# <fullname>-SUFFIX, with the rules copied from SRC.
role() {
  local kind=$1 src=$2 suffix=$3 dest=$4 condition=${5:-}
  grep -q '^rules:$' "$src" || die "$src has no top-level rules: line"
  {
    echo "$HEADER from $src. Don't edit."
    if [[ -n $condition ]]; then echo "{{- if $condition }}"; fi
    echo "apiVersion: rbac.authorization.k8s.io/v1"
    echo "kind: $kind"
    echo "metadata:"
    echo "  name: {{ include \"mode-operator.resourceName\" (dict \"suffix\" \"$suffix\" \"context\" $) }}"
    if [[ $kind == Role ]]; then echo "  namespace: {{ .Release.Namespace }}"; fi
    echo "  labels:"
    echo "    {{- include \"mode-operator.labels\" . | nindent 4 }}"
    sed -n '/^rules:$/,$p' "$src"
    if [[ -n $condition ]]; then echo "{{- end }}"; fi
  } >"$dest"
}

# with_resource_names FILE VALUE: replace the resourceNames list in a
# generated role with the list in VALUE.
with_resource_names() {
  local file=$1 value=$2
  grep -q '^  resourceNames:$' "$file" || die "$file has no resourceNames list"
  awk -v value="$value" '
    skipping && /^  - / { next }
    { skipping = 0 }
    /^  resourceNames:$/ {
      print
      print "  {{- toYaml " value " | nindent 2 }}"
      skipping = 1
      next
    }
    { print }
  ' "$file" >"$file.tmp"
  mv "$file.tmp" "$file"
}

# admission SRC DEST: a ValidatingAdmissionPolicy or its binding, named
# <fullname>-NAME where NAME is its name in SRC. A binding's policyName is
# renamed the same way.
admission() {
  local src=$1 dest=$2
  grep -q '{{' "$src" && die "$src contains {{, which Helm would read as a template"
  grep -q '^  name: ' "$src" || die "$src has no metadata.name"
  grep -qE "^  (name|policyName): [\"']" "$src" && die "$src quotes a name; write it bare"
  grep -q '^  labels:$' "$src" && die "$src has labels, which the chart sets"
  {
    echo "$HEADER from $src. Don't edit."
    awk '
      function named(name) {
        return "{{ include \"mode-operator.resourceName\" (dict \"suffix\" \"" name "\" \"context\" $) }}"
      }
      /^  name: / && !done {
        print "  name: " named($2)
        print "  labels:"
        print "    {{- include \"mode-operator.labels\" . | nindent 4 }}"
        done = 1
        next
      }
      /^  policyName: / { print "  policyName: " named($2); next }
      { print }
    ' "$src"
  } >"$dest"
}

mkdir -p "$CHART/crd" "$CHART/rbac" "$CHART/admission"
# Remove what an earlier run generated, so a role or CRD dropped from config/
# also leaves the chart. Hand-written templates don't have the header.
for f in "$CHART"/crd/*.yaml "$CHART"/rbac/*.yaml "$CHART"/admission/*.yaml; do
  [[ -e $f ]] || continue
  if [[ $(head -n 1 "$f") == "$HEADER"* ]]; then rm "$f"; fi
done

crd config/crd/bases/mode.bitasylum.org_clustermodes.yaml "$CHART/crd/clustermodes.yaml"
crd config/crd/bases/mode.bitasylum.org_clustermodedefinitions.yaml "$CHART/crd/clustermodedefinitions.yaml"

role ClusterRole config/rbac/role.yaml controller "$CHART/rbac/controller-clusterrole.yaml"
role Role config/rbac/leader_election_role.yaml leader-election "$CHART/rbac/leader-election-role.yaml"
role ClusterRole config/rbac/metrics_auth_role.yaml metrics-auth "$CHART/rbac/metrics-auth-clusterrole.yaml" \
  '.Values.metrics.enabled'
role ClusterRole config/rbac/metrics_reader_role.yaml metrics-reader "$CHART/rbac/metrics-reader-clusterrole.yaml" \
  '.Values.metrics.enabled'
role ClusterRole config/rbac/clustermode_maintainer_role.yaml clustermode-maintainer \
  "$CHART/rbac/clustermode-maintainer-clusterrole.yaml"
role ClusterRole config/rbac/clustermode_viewer_role.yaml clustermode-viewer \
  "$CHART/rbac/clustermode-viewer-clusterrole.yaml"
role ClusterRole config/rbac/clustermodedefinition_viewer_role.yaml clustermodedefinition-viewer \
  "$CHART/rbac/clustermodedefinition-viewer-clusterrole.yaml"
role ClusterRole config/rbac/clustermodedefinition_admin_role.yaml clustermodedefinition-admin \
  "$CHART/rbac/clustermodedefinition-admin-clusterrole.yaml"

# The mode manager's writer role is limited to the ClusterModes in the
# chart's values rather than config/'s "default".
role ClusterRole config/mode-manager/rbac/clustermode_writer_role.yaml clustermode-writer \
  "$CHART/rbac/clustermode-writer-clusterrole.yaml" '.Values.modeManager.clusterModes'
with_resource_names "$CHART/rbac/clustermode-writer-clusterrole.yaml" '.Values.modeManager.clusterModes'

admission config/admission/transitions_policy.yaml "$CHART/admission/transitions-policy.yaml"
admission config/admission/transitions_policy_binding.yaml "$CHART/admission/transitions-policy-binding.yaml"
